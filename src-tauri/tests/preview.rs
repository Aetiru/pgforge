use serde::de::DeserializeOwned;
use serde_json::{json, Value};

/// Deserializa la carga como lo haría Tauri al recibir el `invoke`.
fn payload<T: DeserializeOwned>(value: Value) -> T {
    serde_json::from_value(value).expect("la interfaz manda una carga que el comando no entiende")
}

