#[test]
fn un_update_lleva_los_valores_originales_para_detectar_el_conflicto() {
    let changes: Vec<Change> = payload(json!([{
        "kind": "update",
        "key": ["7"],
        "original": { "correo": "viejo@ejemplo" },
        "changes": { "correo": "nuevo@ejemplo" }
    }]));

    let statement = &commands::data::data_preview(shape(), changes).unwrap()[0];
    assert!(
        statement.sql.starts_with("UPDATE public.clientes"),
        "{}",
        statement.sql
    );
    // El valor viejo viaja como parámetro: es lo que hace que un cambio ajeno se reporte como
    // conflicto en vez de pisarse.
    assert!(statement
        .params
        .iter()
        .any(|p| p.as_deref() == Some("viejo@ejemplo")));
    assert!(statement
        .params
        .iter()
        .any(|p| p.as_deref() == Some("nuevo@ejemplo")));
}

