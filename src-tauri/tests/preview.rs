//! Los comandos de vista previa, ejercitados con la carga que manda la interfaz.
//!
//! Estos comandos no tocan la red: reciben lo que `ipc.ts` serializa y delegan en las funciones
//! puras del núcleo. Por eso se pueden probar sin servidor y sin ventana, y por eso conviene —es la
//! promesa de la vista previa: lo que se muestra es exactamente lo que se va a ejecutar. Si la
//! traducción de argumentos pierde un campo, el usuario aprueba un SQL y se ejecuta otro.
//!
//! Los payloads se arman como **JSON**, no construyendo los tipos de Rust: así lo que se verifica
//! también es el contrato de serde con la interfaz —`camelCase` en todo, enums etiquetados con
//! `kind` (o con `on` en los privilegios)—. Un `rename_all` que se caiga rompe acá.

