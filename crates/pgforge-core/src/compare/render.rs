//! El texto de cada objeto, escrito a partir de lo leído.
//!
//! Sirve para dos cosas a la vez, y por eso vive suelto: es lo que la interfaz muestra lado a lado
//! y es lo que [`super::sync`] emite cuando un objeto falta entero del otro lado. Que sean el mismo
//! generador es lo que garantiza que el SQL propuesto sea exactamente lo que se mostró, y no una
//! reconstrucción parecida.
//!
//! Todo acá es función pura sobre [`super::snapshot`]: no hay servidor al que preguntarle nada.

use crate::ddl::quote_ident;
use crate::ddl::table::Identity;

use super::acl::{self, grantee_sql};
use super::snapshot::{
    AclKind, Column, Function, FunctionKind, NamedDef, ObjectAcl, Policy, PolicyCommand, Sequence,
    Table, Trigger, TriggerEnabled, TypeDef, TypeKind, View,
};

/// `esquema.nombre`, con cada mitad citada solo si hace falta.
pub fn qualified(schema: &str, name: &str) -> String {
    format!("{}.{}", quote_ident(schema), quote_ident(name))
}

/// Un literal de texto: comillas simples y las de adentro dobladas. `quote_ident` no sirve para las
/// etiquetas de una enumeración, que no son identificadores.
fn literal(value: &str) -> String {
    format!("'{}'", value.replace('\'', "''"))
}

/// Una columna tal como se escribe dentro de un `CREATE TABLE`.
pub fn column_clause(column: &Column) -> String {
    let mut sql = format!("{} {}", quote_ident(&column.name), column.type_name);

    if let Some(collation) = &column.collation {
        sql.push_str(&format!(" COLLATE {}", quote_ident(collation)));
    }
    if let Some(expression) = &column.generated {
        sql.push_str(&format!(" GENERATED ALWAYS AS ({expression}) STORED"));
    }
    if let Some(identity) = column.identity {
        sql.push_str(match identity {
            Identity::Always => " GENERATED ALWAYS AS IDENTITY",
            Identity::ByDefault => " GENERATED BY DEFAULT AS IDENTITY",
        });
    }
    if column.not_null {
        sql.push_str(" NOT NULL");
    }
    if let Some(default) = &column.default {
        sql.push_str(&format!(" DEFAULT {default}"));
    }

    sql
}

/// El `CREATE TABLE` de una tabla, sin sus restricciones ni sus índices.
///
/// Van aparte a propósito: una clave foránea puede apuntar a una tabla que todavía no se creó, así
/// que el orden que sirve es todas las tablas primero y las restricciones después.
pub fn create_table(schema: &str, table: &Table) -> String {
    let columns = table
        .columns
        .iter()
        .map(|column| format!("    {}", column_clause(column)))
        .collect::<Vec<_>>()
        .join(",\n");

    let mut sql = format!(
        "CREATE TABLE {} (\n{columns}\n)",
        qualified(schema, &table.name)
    );
    if let Some(partition_by) = &table.partition_by {
        sql.push_str(&format!("\n{partition_by}"));
    }
    sql.push(';');
    sql
}

/// `ALTER TABLE … ADD CONSTRAINT …`, con la definición que devolvió el servidor.
pub fn add_constraint(schema: &str, table: &str, constraint: &NamedDef) -> String {
    format!(
        "ALTER TABLE {} ADD CONSTRAINT {} {};",
        qualified(schema, table),
        quote_ident(&constraint.name),
        constraint.definition
    )
}

pub fn create_view(schema: &str, view: &View, replace: bool) -> String {
    let keyword = match (view.materialized, replace) {
        (true, _) => "CREATE MATERIALIZED VIEW",
        (false, true) => "CREATE OR REPLACE VIEW",
        (false, false) => "CREATE VIEW",
    };
    format!(
        "{keyword} {} AS\n{};",
        qualified(schema, &view.name),
        view.definition.trim_end().trim_end_matches(';')
    )
}

pub fn create_sequence(schema: &str, sequence: &Sequence) -> String {
    let mut sql = format!(
        "CREATE SEQUENCE {}\n    AS {}\n    START WITH {}\n    INCREMENT BY {}\n    \
         MINVALUE {}\n    MAXVALUE {}\n    CACHE {}",
        qualified(schema, &sequence.name),
        sequence.type_name,
        sequence.start,
        sequence.increment,
        sequence.min_value,
        sequence.max_value,
        sequence.cache
    );
    if sequence.cycle {
        sql.push_str("\n    CYCLE");
    }
    sql.push(';');
    sql
}

pub fn create_type(schema: &str, definition: &TypeDef) -> String {
    let name = qualified(schema, &definition.name);

    match definition.kind {
        TypeKind::Enum => {
            let labels = definition
                .labels
                .iter()
                .map(|label| format!("    {}", literal(label)))
                .collect::<Vec<_>>()
                .join(",\n");
            format!("CREATE TYPE {name} AS ENUM (\n{labels}\n);")
        }
        TypeKind::Composite => {
            let fields = definition
                .fields
                .iter()
                .map(|field| format!("    {} {}", quote_ident(&field.name), field.data_type))
                .collect::<Vec<_>>()
                .join(",\n");
            format!("CREATE TYPE {name} AS (\n{fields}\n);")
        }
        TypeKind::Domain => {
            let mut sql = format!(
                "CREATE DOMAIN {name} AS {}",
                definition.base.as_deref().unwrap_or("text")
            );
            if let Some(default) = &definition.default {
                sql.push_str(&format!("\n    DEFAULT {default}"));
            }
            if definition.not_null {
                sql.push_str("\n    NOT NULL");
            }
            for check in &definition.checks {
                sql.push_str(&format!(
                    "\n    CONSTRAINT {} {}",
                    quote_ident(&check.name),
                    check.definition
                ));
            }
            sql.push(';');
            sql
        }
        TypeKind::Range => format!(
            "CREATE TYPE {name} AS RANGE (\n    subtype = {}\n);",
            definition.base.as_deref().unwrap_or("text")
        ),
        TypeKind::Other => unreachable!("snapshot solo trae enum, compuesto, dominio y rango"),
    }
}

/// La tabla entera: el `CREATE TABLE` más lo que cuelga de él. Es lo que se muestra de un lado
/// cuando la tabla no existe del otro.
pub fn describe_table(schema: &str, table: &Table) -> String {
    let mut parts = vec![create_table(schema, table)];
    for constraint in &table.constraints {
        parts.push(add_constraint(schema, &table.name, constraint));
    }
    for index in &table.indexes {
        parts.push(format!("{};", index.definition));
    }
    parts.join("\n")
}

/// La función tal como la escribió el servidor, con un `;` al final para poder pegarla en un script.
///
/// Ya viene como `CREATE OR REPLACE`, con el esquema adentro; reescribirlo hacia el destino es cosa
/// de quien la emite (`Builder::sql`), igual que con el cuerpo de una vista.
pub fn create_function(function: &Function) -> String {
    format!(
        "{};",
        function
            .definition
            .trim_end()
            .trim_end_matches(';')
            .trim_end()
    )
}

/// `DROP FUNCTION` o `DROP PROCEDURE` por firma. Sin `IF EXISTS` ni `CASCADE` a propósito: si algo
/// depende de la función tiene que fallar, no llevarse puesto lo que la usa.
pub fn drop_function(schema: &str, function: &Function) -> String {
    let keyword = match function.kind {
        FunctionKind::Function => "FUNCTION",
        FunctionKind::Procedure => "PROCEDURE",
    };
    format!(
        "DROP {keyword} {}({});",
        qualified(schema, &function.name),
        function.arguments
    )
}

fn trigger_state(enabled: TriggerEnabled) -> &'static str {
    match enabled {
        TriggerEnabled::Origin => "ENABLE",
        TriggerEnabled::Disabled => "DISABLE",
        TriggerEnabled::Replica => "ENABLE REPLICA",
        TriggerEnabled::Always => "ENABLE ALWAYS",
    }
}

pub fn alter_trigger_state(schema: &str, trigger: &Trigger) -> String {
    format!(
        "ALTER TABLE {} {} TRIGGER {};",
        qualified(schema, &trigger.table),
        trigger_state(trigger.enabled),
        quote_ident(&trigger.name)
    )
}

pub fn drop_trigger(schema: &str, trigger: &Trigger) -> String {
    format!(
        "DROP TRIGGER {} ON {};",
        quote_ident(&trigger.name),
        qualified(schema, &trigger.table)
    )
}

/// El disparador y, si no está en el estado de fábrica, lo que lo deja como está.
pub fn describe_trigger(schema: &str, trigger: &Trigger) -> String {
    let mut sql = format!("{};", trigger.definition.trim_end().trim_end_matches(';'));
    if trigger.enabled != TriggerEnabled::Origin {
        sql.push('\n');
        sql.push_str(&alter_trigger_state(schema, trigger));
    }
    sql
}

pub fn command_label(command: PolicyCommand) -> &'static str {
    match command {
        PolicyCommand::All => "ALL",
        PolicyCommand::Select => "SELECT",
        PolicyCommand::Insert => "INSERT",
        PolicyCommand::Update => "UPDATE",
        PolicyCommand::Delete => "DELETE",
    }
}

fn roles_sql(roles: &[String]) -> String {
    if roles.is_empty() {
        return "PUBLIC".to_owned();
    }
    roles
        .iter()
        .map(|role| grantee_sql(role))
        .collect::<Vec<_>>()
        .join(", ")
}

/// `CREATE POLICY` completa. `AS PERMISSIVE` va siempre explícito: es lo que hace que el texto diga
/// lo que es y no lo que PostgreSQL supone cuando falta.
pub fn create_policy(schema: &str, policy: &Policy) -> String {
    let mut sql = format!(
        "CREATE POLICY {} ON {}\n    AS {}\n    FOR {}\n    TO {}",
        quote_ident(&policy.name),
        qualified(schema, &policy.table),
        if policy.permissive {
            "PERMISSIVE"
        } else {
            "RESTRICTIVE"
        },
        command_label(policy.command),
        roles_sql(&policy.roles)
    );
    if let Some(using) = &policy.using {
        sql.push_str(&format!("\n    USING ({using})"));
    }
    if let Some(check) = &policy.with_check {
        sql.push_str(&format!("\n    WITH CHECK ({check})"));
    }
    sql.push(';');
    sql
}

/// `ALTER POLICY` con solo las cláusulas que se pasan. Las expresiones llegan ya reescritas.
pub fn alter_policy(
    schema: &str,
    policy: &Policy,
    roles: bool,
    using: Option<&str>,
    with_check: Option<&str>,
) -> String {
    let mut clauses = Vec::new();
    if roles {
        clauses.push(format!("TO {}", roles_sql(&policy.roles)));
    }
    if let Some(using) = using {
        clauses.push(format!("USING ({using})"));
    }
    if let Some(check) = with_check {
        clauses.push(format!("WITH CHECK ({check})"));
    }
    format!(
        "ALTER POLICY {} ON {}\n    {};",
        quote_ident(&policy.name),
        qualified(schema, &policy.table),
        clauses.join("\n    ")
    )
}

pub fn drop_policy(schema: &str, policy: &Policy) -> String {
    format!(
        "DROP POLICY {} ON {};",
        quote_ident(&policy.name),
        qualified(schema, &policy.table)
    )
}

/// Las sentencias que dejan la seguridad por filas de la tabla como está. Con las dos apagadas, un
/// comentario: un lado vacío sin explicación parece un error de la pantalla.
pub fn describe_row_security(schema: &str, table: &str, enabled: bool, forced: bool) -> String {
    let table = qualified(schema, table);
    let mut lines = Vec::new();
    if enabled {
        lines.push(format!("ALTER TABLE {table} ENABLE ROW LEVEL SECURITY;"));
    }
    if forced {
        lines.push(format!("ALTER TABLE {table} FORCE ROW LEVEL SECURITY;"));
    }
    if lines.is_empty() {
        return "-- sin seguridad por filas".to_owned();
    }
    lines.join("\n")
}

/// El objeto al que apunta un `GRANT`: `TABLE esquema.t`, `FUNCTION esquema.f(tipos)`…
///
/// Los argumentos llegan ya escritos contra el esquema que corresponda; acá solo se pegan.
pub fn acl_target(schema: &str, kind: AclKind, name: &str, arguments: Option<&str>) -> String {
    let qualified_name = qualified(schema, name);
    match kind {
        AclKind::Table => format!("TABLE {qualified_name}"),
        AclKind::Sequence => format!("SEQUENCE {qualified_name}"),
        AclKind::Function => format!("FUNCTION {qualified_name}({})", arguments.unwrap_or("")),
        AclKind::Procedure => format!("PROCEDURE {qualified_name}({})", arguments.unwrap_or("")),
    }
}

/// `GRANT` de lo que tiene cada rol sobre el objeto, para mostrar lado a lado.
pub fn describe_grants(schema: &str, object: &ObjectAcl) -> String {
    let target = acl_target(
        schema,
        object.kind,
        &object.name,
        object.arguments.as_deref(),
    );
    let mut lines = Vec::new();
    for (grantee, privileges) in acl::by_grantee(&object.grants) {
        let simple: Vec<&str> = privileges
            .iter()
            .filter(|(_, grantable)| !**grantable)
            .map(|(privilege, _)| privilege.as_str())
            .collect();
        let with_option: Vec<&str> = privileges
            .iter()
            .filter(|(_, grantable)| **grantable)
            .map(|(privilege, _)| privilege.as_str())
            .collect();
        if !simple.is_empty() {
            lines.push(format!(
                "GRANT {} ON {target} TO {};",
                simple.join(", "),
                grantee_sql(&grantee)
            ));
        }
        if !with_option.is_empty() {
            lines.push(format!(
                "GRANT {} ON {target} TO {} WITH GRANT OPTION;",
                with_option.join(", "),
                grantee_sql(&grantee)
            ));
        }
    }
    if lines.is_empty() {
        return "-- sin permisos para otros roles".to_owned();
    }
    lines.join("\n")
}

pub fn describe_view(schema: &str, view: &View) -> String {
    let mut parts = vec![create_view(schema, view, false)];
    for index in &view.indexes {
        parts.push(format!("{};", index.definition));
    }
    parts.join("\n")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::compare::snapshot::{Field, RelationKind};

    fn column(name: &str, type_name: &str) -> Column {
        Column {
            name: name.to_owned(),
            type_name: type_name.to_owned(),
            not_null: false,
            default: None,
            identity: None,
            generated: None,
            collation: None,
        }
    }

    #[test]
    fn escribe_una_tabla_con_sus_restricciones() {
        let table = Table {
            name: "clientes".to_owned(),
            kind: RelationKind::Ordinary,
            partition_by: None,
            columns: vec![
                Column {
                    not_null: true,
                    identity: Some(Identity::Always),
                    ..column("id", "bigint")
                },
                column("nombre", "text"),
            ],
            constraints: vec![NamedDef {
                name: "clientes_pkey".to_owned(),
                definition: "PRIMARY KEY (id)".to_owned(),
            }],
            indexes: vec![NamedDef {
                name: "clientes_nombre_idx".to_owned(),
                definition: "CREATE INDEX clientes_nombre_idx ON app.clientes USING btree (nombre)"
                    .to_owned(),
            }],
        };

        let sql = describe_table("app", &table);
        assert!(sql.contains("CREATE TABLE app.clientes ("));
        assert!(sql.contains("id bigint GENERATED ALWAYS AS IDENTITY NOT NULL"));
        assert!(
            sql.contains("ALTER TABLE app.clientes ADD CONSTRAINT clientes_pkey PRIMARY KEY (id);")
        );
        assert!(
            sql.contains("CREATE INDEX clientes_nombre_idx ON app.clientes USING btree (nombre);")
        );
    }

    #[test]
    fn una_enumeracion_escapa_sus_valores() {
        let definition = TypeDef {
            name: "estado".to_owned(),
            kind: TypeKind::Enum,
            labels: vec!["activo".to_owned(), "de'baja".to_owned()],
            fields: Vec::new(),
            base: None,
            not_null: false,
            default: None,
            checks: Vec::new(),
        };

        assert_eq!(
            create_type("app", &definition),
            "CREATE TYPE app.estado AS ENUM (\n    'activo',\n    'de''baja'\n);"
        );
    }

    #[test]
    fn un_compuesto_lista_sus_campos() {
        let definition = TypeDef {
            name: "direccion".to_owned(),
            kind: TypeKind::Composite,
            labels: Vec::new(),
            fields: vec![
                Field {
                    name: "calle".to_owned(),
                    data_type: "text".to_owned(),
                    collation: None,
                },
                Field {
                    name: "numero".to_owned(),
                    data_type: "integer".to_owned(),
                    collation: None,
                },
            ],
            base: None,
            not_null: false,
            default: None,
            checks: Vec::new(),
        };

        assert_eq!(
            create_type("app", &definition),
            "CREATE TYPE app.direccion AS (\n    calle text,\n    numero integer\n);"
        );
    }

    #[test]
    fn la_funcion_termina_en_un_solo_punto_y_coma() {
        let function = Function {
            name: "f".to_owned(),
            arguments: "integer".to_owned(),
            kind: FunctionKind::Function,
            definition: "CREATE OR REPLACE FUNCTION app.f(integer)\n RETURNS integer\n \
                         LANGUAGE sql\nAS $function$ SELECT 1 $function$\n"
                .to_owned(),
        };
        let sql = create_function(&function);
        assert!(sql.ends_with("$function$;"));
        // Si ya traía uno, no se duplica.
        let con_punto = Function {
            definition: format!("{};\n", sql.trim_end_matches(';')),
            ..function.clone()
        };
        assert_eq!(create_function(&con_punto), sql);
        assert_eq!(
            drop_function("app", &function),
            "DROP FUNCTION app.f(integer);"
        );
    }

    #[test]
    fn una_politica_escribe_roles_comando_y_condiciones() {
        let policy = Policy {
            table: "pedidos".to_owned(),
            name: "por tenant".to_owned(),
            command: PolicyCommand::Update,
            permissive: false,
            roles: vec!["PUBLIC".to_owned(), "Ana".to_owned()],
            using: Some("(t = 1)".to_owned()),
            with_check: Some("(t = 1)".to_owned()),
        };
        assert_eq!(
            create_policy("app", &policy),
            "CREATE POLICY \"por tenant\" ON app.pedidos\n    AS RESTRICTIVE\n    FOR UPDATE\n    \
             TO PUBLIC, \"Ana\"\n    USING ((t = 1))\n    WITH CHECK ((t = 1));"
        );
    }

    #[test]
    fn los_permisos_se_describen_por_rol() {
        let object = ObjectAcl {
            kind: AclKind::Function,
            name: "f".to_owned(),
            arguments: Some("integer".to_owned()),
            grants: vec![
                crate::compare::snapshot::Grant {
                    grantee: "PUBLIC".to_owned(),
                    privilege: "EXECUTE".to_owned(),
                    grantable: false,
                },
                crate::compare::snapshot::Grant {
                    grantee: "ana".to_owned(),
                    privilege: "EXECUTE".to_owned(),
                    grantable: true,
                },
            ],
        };
        assert_eq!(
            describe_grants("app", &object),
            "GRANT EXECUTE ON FUNCTION app.f(integer) TO PUBLIC;\n\
             GRANT EXECUTE ON FUNCTION app.f(integer) TO ana WITH GRANT OPTION;"
        );
        let vacia = ObjectAcl {
            grants: Vec::new(),
            ..object
        };
        assert!(describe_grants("app", &vacia).starts_with("--"));
    }

    #[test]
    fn la_seguridad_por_filas_sin_nada_encendido_lo_dice() {
        assert!(describe_row_security("app", "t", false, false).starts_with("--"));
        assert_eq!(
            describe_row_security("app", "t", true, true)
                .lines()
                .count(),
            2
        );
    }

    #[test]
    fn una_vista_materializada_no_admite_replace() {
        let view = View {
            name: "ventas".to_owned(),
            materialized: true,
            definition: " SELECT 1;".to_owned(),
            indexes: Vec::new(),
        };
        assert!(create_view("app", &view, true).starts_with("CREATE MATERIALIZED VIEW app.ventas"));
    }
}
